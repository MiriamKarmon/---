export type Q =
    | { type: 'mc'; q: string; choices: string[]; answer: string; explain: string; bonus?: boolean }
    | { type: 'tf'; q: string; answer: boolean; explain: string; bonus?: boolean }
    | { type: 'odd'; q: string; items: string[]; answer: string; explain: string; bonus?: boolean }
    | { type: 'cloze'; before: string; after: string; bank: string[]; answer: string; explain: string; bonus?: boolean }
    | { type: 'table'; q: string; rows: string[]; cols: string[]; correct: number[]; explain: string; bonus?: boolean }
    | { type: 'pick2'; q: string; options: string[]; answers: string[]; explain: string; bonus?: boolean }
    | { type: 'reflect'; q: string; choices: string[]; explain: string; bonus?: boolean };

