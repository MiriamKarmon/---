export interface LevelDef { id: number; name: string; icon: string; }

export interface Pack {
    id: string;
    subject: string;
    worldName: string;
    levels: LevelDef[];
    questions: (level: number) => Q[];
}

function mc(q: string, answer: string, wrongs: string[], explain: string, bonus = false): Q {
    return { type: 'mc', q, choices: [answer, ...wrongs], answer, explain, bonus };
}
function tf(q: string, answer: boolean, explain: string): Q {
    return { type: 'tf', q, answer, explain };
}
function odd(q: string, items: string[], answer: string, explain: string): Q {
    return { type: 'odd', q, items, answer, explain };
}
function cloze(before: string, after: string, bank: string[], answer: string, explain: string): Q {
    return { type: 'cloze', before, after, bank, answer, explain };
}
function table(q: string, rows: string[], cols: string[], correct: number[], explain: string): Q {
    return { type: 'table', q, rows, cols, correct, explain };
}
function pick2(q: string, options: string[], answers: string[], explain: string): Q {
    return { type: 'pick2', q, options, answers, explain };
}

